//! Fragments: several packages assemble one file.
mod common;

use std::fs;

use common::*;
use dots_files::*;
use serde_json::json;

const BASE: &str = "[core]\n\teditor = nvim\n\tpager = delta\n[user]\n\tname = Ofir\n";
const DELTA: &str = "[delta]\n\tnavigate = true\n\tside-by-side = true\n[interactive]\n\tdiffFilter = delta --color-only\n";

fn fragment(e: &Env, pkg: &str, src: &str, text: &str, priority: Option<i64>) -> ResolvedFile {
    e.write(&format!("{pkg}/{src}"), text);
    let mut entry =
        json!({"dst": "~/.gitconfig", "mode": "fragment", "format": "gitconfig", "src": src});
    if let Some(p) = priority {
        entry["priority"] = json!(p);
    }
    let entry: dots_model::FileEntry = serde_json::from_value(entry).unwrap();
    resolve_entry(
        pkg,
        &e.root.join(pkg),
        &entry,
        &e.ctx("r"),
        &|_| Ok(true),
        &[],
    )
    .unwrap()
    .unwrap()
}

#[test]
fn gitconfig_composition() {
    let e = env();
    let base = fragment(&e, "base", "gitconfig.fragment", BASE, Some(0));
    let delta = fragment(&e, "delta", "gitconfig.fragment", DELTA, Some(50));
    assert_eq!(delta.extras.fragment, Some(50));
    // Listed out of order: the composition sorts by priority, lowest first.
    let files = compose_fragments(vec![delta.clone(), base.clone()]);
    assert_eq!(files.len(), 1);
    assert_eq!(files[0].package, FRAGMENT_OWNER);
    let ctx = e.ctx("r1");
    let out = render_layers(&files[0], &ctx).unwrap();
    golden(
        "gitconfig-composed.txt",
        &out.replace(&e.home.display().to_string(), "<HOME>")
            .replace("<HOME>\\", "<HOME>/"),
    );
    assert!(out.contains("[core]") && out.contains("[user]"), "{out}");
    assert!(
        out.contains("[delta]\n\tnavigate = true") && out.contains("[interactive]"),
        "{out}"
    );
    assert!(out.find("[core]").unwrap() < out.find("[delta]").unwrap());

    // Apply: one owned file, linked into place.
    let steps = plan(&files, &ctx);
    assert_eq!(steps.len(), 1);
    assert_eq!(steps[0].action, Action::Create);
    assert_eq!(
        steps[0].layers,
        vec!["base/gitconfig.fragment", "delta/gitconfig.fragment"]
    );
    assert_eq!(apply(&steps[0], &ctx).status, OutcomeStatus::Applied);
    let on_disk = fs::read_to_string(e.home.join(".gitconfig")).unwrap();
    assert_eq!(on_disk, out);
    assert_eq!(plan(&files, &ctx)[0].action, Action::Unchanged);

    // Removing `delta` re-renders the same owned file, dropping only [delta].
    let files = compose_fragments(vec![base.clone()]);
    let steps = plan(&files, &ctx);
    assert_eq!(steps[0].action, Action::Update, "{:?}", steps[0].error);
    assert_eq!(apply(&steps[0], &ctx).status, OutcomeStatus::Applied);
    let after = fs::read_to_string(e.home.join(".gitconfig")).unwrap();
    assert!(
        after.contains("[core]\n\teditor = nvim") && after.contains("[user]"),
        "{after}"
    );
    assert!(
        !after.contains("[delta]") && !after.contains("[interactive]"),
        "{after}"
    );
    golden(
        "gitconfig-without-delta.txt",
        &after
            .replace(&e.home.display().to_string(), "<HOME>")
            .replace("<HOME>\\", "<HOME>/"),
    );
    assert!(plan_removals(&plan(&files, &ctx), &ctx, None).is_empty());

    // Once nobody contributes, the file is no longer wanted and goes.
    let removals = plan_removals(&[], &ctx, None);
    assert_eq!(removals.len(), 1);
    assert_eq!(removals[0].action, Action::Remove);
    assert_eq!(apply(&removals[0], &ctx).status, OutcomeStatus::Applied);
    assert!(!e.home.join(".gitconfig").exists());
}

#[test]
fn header_names_each_contributor() {
    let e = env();
    let files = compose_fragments(vec![
        fragment(&e, "base", "g", BASE, Some(0)),
        fragment(&e, "delta", "g", DELTA, Some(50)),
    ]);
    let out = render_layers(&files[0], &e.ctx("r")).unwrap();
    assert!(
        out.starts_with("# Generated by dots from fragments."),
        "{out}"
    );
    assert!(
        out.contains("# fragments: base (priority 0, base/g), delta (priority 50, delta/g)"),
        "{out}"
    );
}

#[test]
fn priority_decides_order_and_the_later_wins_a_shared_key() {
    let e = env();
    let a = fragment(&e, "a", "g", "[core]\n\teditor = vi\n", Some(10));
    let b = fragment(
        &e,
        "b",
        "g",
        "[core]\n\teditor = nvim\n\tpager = less\n",
        Some(20),
    );
    let out = render_layers(
        &compose_fragments(vec![b.clone(), a.clone()])[0],
        &e.ctx("r"),
    )
    .unwrap();
    assert!(
        out.contains("editor = nvim")
            && !out.contains("editor = vi")
            && out.contains("pager = less"),
        "{out}"
    );
    // Default priority is 0 and ties go by package name, so the result does not depend on order.
    let c = fragment(&e, "c", "g", "[x]\n\tk = 1\n", None);
    let d = fragment(&e, "d", "g", "[y]\n\tk = 1\n", None);
    let one = render_layers(
        &compose_fragments(vec![c.clone(), d.clone()])[0],
        &e.ctx("r"),
    )
    .unwrap();
    let two = render_layers(&compose_fragments(vec![d, c])[0], &e.ctx("r")).unwrap();
    assert_eq!(one, two);
}

#[test]
fn same_key_at_the_same_priority_is_a_collision() {
    let e = env();
    let a = fragment(&e, "a", "g", "[core]\n\teditor = vi\n", Some(5));
    let b = fragment(&e, "b", "g", "[core]\n\teditor = nvim\n", Some(5));
    let files = compose_fragments(vec![a, b]);
    let steps = plan(&files, &e.ctx("r"));
    assert_eq!(steps[0].action, Action::Failed);
    let d = steps[0].error.clone().unwrap();
    assert_eq!(d.code, "fragment-collision");
    assert!(
        d.message.contains("core.editor") && d.message.contains("`a`") && d.message.contains("`b`"),
        "{}",
        d.message
    );
    assert_eq!(d.provenance.len(), 2);
    // Sections shared by two fragments are fine while their keys differ.
    let a = fragment(&e, "a", "g", "[core]\n\teditor = vi\n", Some(5));
    let b = fragment(&e, "b", "g", "[core]\n\tpager = less\n", Some(5));
    let out = render_layers(&compose_fragments(vec![a, b])[0], &e.ctx("r")).unwrap();
    assert!(out.contains("editor = vi") && out.contains("pager = less"));
}

#[test]
fn collision_lint_works_on_sources() {
    let src = |pkg: &str, p: i64, fmt: &str, text: &str| FragmentSource {
        package: pkg.into(),
        priority: p,
        format: fmt.into(),
        path: format!("packages/{pkg}/f"),
        text: text.into(),
    };
    let ds = lint_collisions(
        "~/.gitconfig",
        &[
            src(
                "a",
                0,
                "gitconfig",
                "[core]\n\teditor = vi\n\tpager = less\n",
            ),
            src(
                "b",
                0,
                "gitconfig",
                "[core]\n\teditor = vi\n\tpager = more\n",
            ),
            src("c", 1, "gitconfig", "[core]\n\teditor = vi\n"),
            src("d", 0, "gitconfig", "[user]\nname = x\n"),
        ],
    );
    let keys: Vec<&str> = ds.iter().map(|d| d.message.as_str()).collect();
    assert_eq!(ds.len(), 2, "{keys:?}");
    assert!(ds.iter().all(|d| d.code == "fragment-collision"));
    assert!(ds[0].message.contains("core.editor") && ds[1].message.contains("core.pager"));
    // TOML, JSON and YAML are compared by key path; text and unparseable sources are skipped.
    let ds = lint_collisions(
        "~/x.toml",
        &[
            src("a", 0, "toml", "[t]\nk = 1\n"),
            src("b", 0, "toml", "[t]\nk = 2\nj = 3\n"),
        ],
    );
    assert_eq!(ds.len(), 1);
    assert!(ds[0].message.contains("t.k"));
    let ds = lint_collisions(
        "~/x.json",
        &[
            src("a", 0, "json", r#"{"a": {"b": 1}}"#),
            src("b", 0, "json", r#"{"a": {"c": 1}}"#),
        ],
    );
    assert!(ds.is_empty());
    let ds = lint_collisions(
        "~/x",
        &[
            src("a", 0, "text", "k = 1"),
            src("b", 0, "text", "k = 1"),
            src("c", 0, "toml", "k = @dots(x)@"),
        ],
    );
    assert!(ds.is_empty());
}

#[test]
fn text_fragments_are_concatenated_with_banners() {
    let e = env();
    e.write("a/z", "export A=1\n");
    e.write("b/z", "export B=1\n");
    let mk = |pkg: &str, prio: i64| {
        let entry: dots_model::FileEntry = serde_json::from_value(
            json!({"dst": "~/.aliases", "mode": "fragment", "src": "z", "priority": prio}),
        )
        .unwrap();
        resolve_entry(
            pkg,
            &e.root.join(pkg),
            &entry,
            &e.ctx("r"),
            &|_| Ok(true),
            &[],
        )
        .unwrap()
        .unwrap()
    };
    let files = compose_fragments(vec![mk("b", 2), mk("a", 1)]);
    let out = render_layers(&files[0], &e.ctx("r")).unwrap();
    let text = out.lines().skip(2).collect::<Vec<_>>().join("\n");
    assert_eq!(
        text,
        "# --- dots: fragment from package `a` (priority 1, a/z) ---\nexport A=1\n# --- dots: fragment from package `b` (priority 2, b/z) ---\nexport B=1"
    );
}

#[test]
fn fragments_use_their_own_packages_directives_and_settings() {
    let e = env();
    let mut ctx = e.ctx("r");
    ctx.settings = vec![
        setting("delta.side", json!(true), "machine"),
        setting("base.name", json!("Ofir"), "default"),
        setting("name", json!("global"), "default"),
    ];
    let a = fragment(
        &e,
        "base",
        "g",
        "[user]\n\tname = @dots(setting.name)@\n",
        Some(0),
    );
    let b = fragment(
        &e,
        "delta",
        "g",
        "[delta]\n# dots:if setting.side\n\tside-by-side = true\n# dots:end\n",
        Some(1),
    );
    let out = render_layers(&compose_fragments(vec![a, b])[0], &ctx).unwrap();
    assert!(
        out.contains("name = Ofir") && out.contains("side-by-side = true"),
        "{out}"
    );
    assert!(
        out.contains("base.name=Ofir(default)") && out.contains("delta.side=true(machine)"),
        "{out}"
    );
}

#[test]
fn fragment_set_patches_apply_to_the_contribution() {
    let e = env();
    e.write("a/c.toml", "[t]\nk = 1\n");
    e.write("b/c.toml", "[u]\nj = 1\n");
    let mk = |pkg: &str, extra: serde_json::Value| {
        let mut v = json!({"dst": "~/x.toml", "mode": "fragment", "src": "c.toml"});
        v.as_object_mut()
            .unwrap()
            .extend(extra.as_object().unwrap().clone());
        let entry: dots_model::FileEntry = serde_json::from_value(v).unwrap();
        resolve_entry(
            pkg,
            &e.root.join(pkg),
            &entry,
            &e.ctx("r"),
            &|_| Ok(true),
            &[],
        )
        .unwrap()
        .unwrap()
    };
    let a = mk(
        "a",
        json!({"priority": 0, "set": [{"path": "t.k", "value": "@dots(setting.font_size)@"}]}),
    );
    let b = mk("b", json!({"priority": 1}));
    let out = render_layers(&compose_fragments(vec![a, b])[0], &e.ctx("r")).unwrap();
    assert!(out.contains("k = 15") && out.contains("[u]"), "{out}");
}

#[test]
fn mixed_formats_and_other_entries_are_handled() {
    let e = env();
    let a = fragment(&e, "a", "g", "[a]\nx = 1\n", Some(0));
    let mut b = fragment(&e, "b", "g", "[b]\ny = 1\n", Some(1));
    b.format = "toml".into();
    let d = render_layers(&compose_fragments(vec![a.clone(), b])[0], &e.ctx("r")).unwrap_err();
    assert_eq!(d.code, "schema-invalid-value");
    // Non-fragment files pass through in place; the composed file takes the first fragment's slot.
    e.write("l/plain", "x\n");
    let plain = e.file("p", "other", &["l/plain"], "text");
    let a2 = fragment(&e, "z", "g", "[z]\nx = 1\n", Some(1));
    let out = compose_fragments(vec![plain.clone(), a, plain.clone(), a2]);
    assert_eq!(out.len(), 3);
    assert_eq!(out[0].package, "p");
    assert_eq!(out[1].package, FRAGMENT_OWNER);
    assert_eq!(out[2].package, "p");
    assert_eq!(out[1].extras.parts.len(), 2);
}

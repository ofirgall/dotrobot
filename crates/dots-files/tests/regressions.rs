//! Regressions from the review: comment leaders, shebangs, nested `dots:if!`, CRLF.
mod common;

use common::*;
use dots_files::*;
use dots_model::{FileEntry, PlatformString};
use std::path::Path;

fn with_leader(
    e: &Env,
    dst: &str,
    text: &str,
    format: &str,
) -> Result<String, dots_core::Diagnostic> {
    e.write("l/one", text);
    let mut f = e.file("pkg", dst, &["l/one"], format);
    f.comment = infer_comment(format, &f.dst).to_string();
    render_layers(&f, &e.ctx("r"))
}

#[test]
fn comment_leader_is_inferred_from_the_destination() {
    let cases = [
        ("init.lua", "--"),
        ("x.vim", "\""),
        (".vimrc", "\""),
        ("vimrc", "\""),
        ("kanata.kbd", ";;"),
        ("init.el", ";"),
        ("a.lisp", ";"),
        ("q.sql", "--"),
        ("x.json5", "//"),
        ("config", "#"),
        ("tmux.conf", "#"),
    ];
    for (dst, want) in cases {
        assert_eq!(infer_comment("text", Path::new(dst)), want, "{dst}");
    }
    assert_eq!(infer_comment("jsonc", Path::new("settings.json")), "//");
}

#[test]
fn lua_directives_and_header_use_the_lua_leader() {
    let e = env();
    let src = "-- dots:if setting.cursor_shader\non = 1\n-- dots:else\noff = 1\n-- dots:end\n";
    let out = with_leader(&e, "init.lua", src, "text").unwrap();
    assert!(out.starts_with("-- "), "header uses `--`: {out}");
    assert!(
        out.contains("on = 1\n") && !out.contains("off = 1"),
        "{out}"
    );
    assert!(!out.contains("dots:if"), "{out}");
}

#[test]
fn directives_behind_the_wrong_leader_are_an_error_with_a_hint() {
    let e = env();
    e.write(
        "l/one",
        "-- dots:if setting.cursor_shader\non = 1\n-- dots:end\n",
    );
    let f = e.file("pkg", "init.lua", &["l/one"], "text"); // helper default leader `#`
    let d = render_layers(&f, &e.ctx("r")).unwrap_err();
    assert_eq!(d.code, "directive-error");
    assert!(d.hint.contains("comment = "), "{}", d.hint);
    // The same check without a render.
    e.write(
        "pkg/init.lua.src",
        "-- dots:if os = \"macos\"\nx\n-- dots:end\n",
    );
    let entry = FileEntry {
        dst: Some(PlatformString::Plain("~/.config/x/other.conf".into())),
        mode: Some("render".into()),
        src: Some("init.lua.src".into()),
        ..Default::default()
    };
    let found = lint_layers(&e.root.join("pkg"), &entry);
    assert_eq!(found.len(), 1, "{found:?}");
    let ok = FileEntry {
        dst: Some(PlatformString::Plain("~/.config/x/init.lua".into())),
        ..entry.clone()
    };
    assert!(lint_layers(&e.root.join("pkg"), &ok).is_empty());
    let explicit = FileEntry {
        comment: Some("--".into()),
        ..entry
    };
    assert!(lint_layers(&e.root.join("pkg"), &explicit).is_empty());
}

#[test]
fn header_goes_below_a_shebang() {
    let e = env();
    let out = e.one("text", "#!/bin/sh\necho hi\n").unwrap();
    assert!(out.starts_with("#!/bin/sh\n"), "{out}");
    assert!(out.contains("Generated by dots"), "{out}");
    assert!(out.ends_with("echo hi\n"), "{out}");
    // Without a shebang the header is still first.
    let out = e.one("text", "echo hi\n").unwrap();
    assert!(
        out.starts_with('#') && out.contains("Generated by dots"),
        "{out}"
    );
}

#[test]
fn nested_if_inside_a_bang_body_stays_commented_in_every_branch() {
    let e = env();
    let src = "\
# dots:if! setting.cursor_shader
# a = 1
# dots:if os = \"macos\"
# b = 2
# dots:else
# c = 3
# dots:end
# dots:end
";
    let out = e.one("text", src).unwrap();
    assert!(out.contains("a = 1\n") && out.contains("b = 2\n"), "{out}");
    assert!(!out.contains("c = 3"), "{out}");
    assert!(!out.contains("# b = 2"), "{out}");
    // The else branch of the nested chain is commented too.
    let src = src.replace("os = \\\"macos\\\"", "os = \\\"linux\\\"");
    let src = src.replace("os = \"macos\"", "os = \"linux\"");
    let out = e.one("text", &src).unwrap();
    assert!(out.contains("\nc = 3\n"), "{out}");
    assert!(!out.contains("# c = 3"), "{out}");
}

#[test]
fn crlf_layers_stay_crlf_with_directives() {
    let e = env();
    let out = e
        .one(
            "text",
            "a = 1\r\n# dots:if setting.cursor_shader\r\nb = @dots(setting.font_size)@\r\n# dots:end\r\nz\r\n",
        )
        .unwrap();
    assert!(out.contains("a = 1\r\nb = 15\r\nz\r\n"), "{out:?}");
    let body: Vec<&str> = out.split("\r\n").collect();
    assert!(body.iter().all(|l| !l.contains('\n')), "{out:?}");
}
